#!/usr/bin/env python3
"""Build every generated index from frontmatter and registry rows. No model call, no network.

Outputs:
  packs/<pack>/INDEX.md          one row per knowledge file of the pack (all packs)
  core/<name>.md                 for each registry_rows/<name>.md: core rows + rows of active packs
                                 (router.md, where_to_look.md, entities.md, contacts.md ...)
  .claude/skills/<n>/SKILL.md    pointer to core/skills/<n> or packs/<p>/skills/<n> (Claude Code)
  .agents/skills/<n>/SKILL.md    the same pointer for Codex

Usage:
  python3 core/scripts/build_indexes.py           # print what would change
  python3 core/scripts/build_indexes.py --write   # write
  python3 core/scripts/build_indexes.py --check   # exit 1 if a generated file is out of date
"""
from __future__ import annotations
import argparse
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import ROOT, cells, frontmatter, pack_dirs, pack_files  # noqa: E402

MARK = '<!-- GENERATED by core/scripts/build_indexes.py. Do not edit by hand. -->'
PROBLEMS: list[str] = []  # registry column mismatches found by merged_registries()
POINTER_ROOTS = ('.claude/skills', '.agents/skills')


def pack_index(pack: Path) -> str:
    rows = []
    for f in pack_files(pack):
        fm = frontmatter(f) or {}
        rel = f.relative_to(pack).as_posix()
        title = fm.get('title') or fm.get('name') or f.stem
        rows.append(f"| {title} | {fm.get('type', '?')} | {fm.get('status', '?')} | "
                    f"{fm.get('valid_from', '')} | `{rel}` |")
    out = [MARK, '', f'# {pack.name} pack index', '',
           '| Title | Type | Status | Valid from | File |', '|---|---|---|---|---|', *rows]
    if not rows:
        out.append('| (no files yet) | | | | |')
    return '\n'.join(out) + '\n'


def first_table(path: Path) -> tuple[list[str], list[list[str]]]:
    """Header cells and data rows of the first Markdown table in a file."""
    head, rows = [], []
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line.startswith('|'):
            if head:
                break
            continue
        if set(line.replace('|', '').strip()) <= set('-: '):
            continue
        c = cells(line)
        if not head:
            head = c
        elif len(c) == len(head):
            rows.append(c)
    return head, rows


def merged_registries() -> dict[str, str]:
    sources: dict[str, list[tuple[str, Path]]] = {}
    for owner, base in [('core', ROOT / 'core')] + [(p.name, p) for p in pack_dirs()]:
        for f in sorted((base / 'registry_rows').glob('*.md')):
            sources.setdefault(f.name, []).append((owner, f))
    out = {}
    for name, items in sorted(sources.items()):
        header, body = None, []
        for owner, f in items:
            head, rows = first_table(f)
            header = header or head
            if head != header:
                PROBLEMS.append(f'{f.relative_to(ROOT)}: columns {head} differ from {header}; its rows are not merged')
            body += [f"| {' | '.join(r)} | {owner} |" for r in rows if len(r) == len(header)]
        title = name[:-3].replace('_', ' ')
        out[f'core/{name}'] = '\n'.join([
            MARK, '', f'# {title} (merged)', '',
            f'Source rows: `core/registry_rows/{name}` and `packs/<active pack>/registry_rows/{name}`.', '',
            f"| {' | '.join(header)} | Pack |", '|' + '---|' * (len(header) + 1), *body]) + '\n'
    return out


def skill_dirs() -> list[Path]:
    dirs = sorted(d.parent for d in (ROOT / 'core/skills').glob('*/SKILL.md'))
    for p in pack_dirs():
        dirs += sorted(d.parent for d in (p / 'skills').glob('*/SKILL.md'))
    return dirs


def pointer(skill: Path) -> str:
    fm = frontmatter(skill / 'SKILL.md') or {}
    rel = (skill / 'SKILL.md').relative_to(ROOT).as_posix()
    desc = str(fm.get('description', '')).replace('\n', ' ').replace("'", "''")
    return (f"---\nname: {skill.name}\ndescription: '{desc}'\n---\n\n{MARK}\n\n"
            f'Read and follow `{rel}` from the repository root. That file is the canonical skill.\n')


def outputs() -> dict[str, str]:
    """Relative path -> expected content, for every generated file."""
    out = {}
    for p in sorted(x for x in (ROOT / 'packs').iterdir() if (x / 'pack.yaml').is_file() and not x.name.startswith('_')):
        out[(p / 'INDEX.md').relative_to(ROOT).as_posix()] = pack_index(p)
    out.update(merged_registries())
    names = {}
    for s in skill_dirs():
        if s.name in names:
            raise SystemExit(f'Two skills have the name {s.name}: {names[s.name]} and {s}')
        names[s.name] = s
        for r in POINTER_ROOTS:
            out[f'{r}/{s.name}/SKILL.md'] = pointer(s)
    return out


def stale_pointers(expected: dict[str, str]) -> list[Path]:
    """Generated pointer folders that no longer have a canonical skill."""
    stale = []
    for r in POINTER_ROOTS:
        for f in (ROOT / r).glob('*/SKILL.md'):
            rel = f.relative_to(ROOT).as_posix()
            if rel not in expected and MARK in f.read_text(encoding='utf-8'):
                stale.append(f.parent)
    return stale


def drift(exp: dict[str, str] | None = None) -> list[str]:
    PROBLEMS.clear()
    exp = outputs() if exp is None else exp
    errs = [f'{rel} is out of date' for rel, text in exp.items()
            if not (ROOT / rel).is_file() or (ROOT / rel).read_text(encoding='utf-8') != text]
    errs += [f'{d.relative_to(ROOT)} is a stale skill pointer' for d in stale_pointers(exp)]
    errs += PROBLEMS
    return errs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    exp = outputs()
    errs = drift(exp)
    if a.check:
        print('\n'.join(errs) or 'PASS: generated indexes are up to date')
        return 1 if errs else 0
    if not a.write:
        print('\n'.join(errs) or 'Nothing to change')
        return 0
    for rel, text in exp.items():
        f = ROOT / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        if not f.is_file() or f.read_text(encoding='utf-8') != text:
            f.write_text(text, encoding='utf-8')
            print(f'wrote {rel}')
    for d in stale_pointers(exp):
        shutil.rmtree(d)
        print(f'removed {d.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
